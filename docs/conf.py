# Members generated by Django that only add noise to the reference pages.
_SKIPPED_MEMBER_NAMES = {
    "Meta",
    "DoesNotExist",
    "MultipleObjectsReturned",
    "objects",
    "base_fields",
    "declared_fields",
    "media",
}


def _skip_django_internals(app, what, name, obj, skip, options):
    """Hide Django field descriptors and auto-generated model helpers.

    Model fields and relations are described in each model's ``Attributes``
    section instead, which is easier to read than the descriptor docstrings
    Django would otherwise contribute.
    """
    if name in _SKIPPED_MEMBER_NAMES:
        return True
    if isinstance(obj, functools.partialmethod):
        # get_<field>_display, get_next_by_<field>, ... added by Django.
        return True
    module = type(obj).__module__
    if not inspect.isclass(obj) and module.startswith("django.db.models"):
        # Field/relation descriptors and managers (the model classes
        # themselves also have a django.db.models metaclass, so keep classes).
        return True
    return skip


def setup(app):
    """Register the autodoc filter defined above."""
    app.connect("autodoc-skip-member", _skip_django_internals)


